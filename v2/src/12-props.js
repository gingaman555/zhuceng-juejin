/* 哪一格放什麼裝飾。

   用組別與里程碑算，不擲骰子——同一條走廊每次打開，石頭都在同一個
   地方。畫面每重畫一次石頭就跳一次的話，那條走廊就不是一個地方了。 */
function propFor(seed, i) {
  var h = hash(seed + '#' + i);
  var r = h % 100;
  if (r < 14) return 'rubble';
  if (r < 22) return 'crystal';
  if (r < 30) return 'shroom';
  return '';
}

/* 鐘乳石掛在哪、哪一根。同樣是算出來的。 */
function dripFor(seed, i) {
  var h = hash(seed + '@' + i);
  if (h % 100 < 42) return null;
  return { px: (h % 2 ? DRIP.a : DRIP.b), off: (h >> 4) % 22 };
}
