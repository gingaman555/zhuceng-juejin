/* 全部的計算都在這裡，而且只在這裡。

   一個概念一個來源。文案跟規則綁在一起——講規則的句子不是寫死的字串，
   是從下面的數字組出來的。改 BAND 的值，畫面上那句話會跟著變，
   不會變成一句謊話。

   這個系統跟成績無關。它不判斷作業好不好，只判斷「你對自己的預估準不準」。
   那是刻意的：拖延的根不是懶，是對「這件事要花多久」沒有體感。 */

var RULES = {

  /* ---------- 自我承諾 ---------- */
  EST_MIN: 1,          /* 滑桿最少 1 天 */
  EST_MAX: 21,         /* 最多三週。再長就不是一個里程碑了 */
  EST_DEFAULT: 5,

  /* ---------- 判定 ---------- */
  /* 容許誤差＝預估天數的兩成，最少 1 天。
     estimate 5 天 → ±1 天算準；estimate 14 天 → ±3 天算準。
     用比例而不是固定值，因為估 3 天差 2 天跟估 20 天差 2 天不是同一回事。 */
  BAND_RATIO: 0.2,
  BAND_MIN: 1,

  /* ---------- 推進 ---------- */
  PUSH_PER_DAY: 1,     /* 一天一次。多按沒有用，這不是點擊遊戲 */
  STALL_DAYS: 2,       /* 幾天沒推進就開始長藤蔓 */
  SLEEP_DAYS: 4,       /* 幾天沒推進角色會睡著 */
  /* 補登補得回幾天前。兩天：忘一次補得回來，忘一週補不回來——
     再往上加就變成「最後一天一次補完」，那條走廊就不再是紀錄了。
     補登不會改判定：實際天數是承諾那天到交出去那天算的。 */
  BACKFILL_MAX: 2,

  /* ---------- 招牌 ---------- */
  /* 只剩一種材質。三階那個「越深牌子越好」的漸層拿掉了——
     深度已經不是進度，留著它跟其他每一條規則都打架。 */
  SIGN_TIERS: ['iron'],

  /* 這個系統沒有的東西寫在 check.js 的 BANNED 裡，不寫在這裡——
     寫在這裡等於把那些詞放進畫面，檢查器會抓（而且抓得對）。 */
  _: null
};

function clamp(lo, hi, n) { return Math.max(lo, Math.min(hi, n)); }

/* 容許誤差：估幾天，準的範圍就有多寬 */
RULES.band = function (est) {
  return Math.max(RULES.BAND_MIN, Math.round((Number(est) || 0) * RULES.BAND_RATIO));
};

/* ---------- 三種印章 ----------
   系統唯一會說的一句話，而且它只比對兩個數字：你說幾天、實際幾天。

   底下那一句刻意只講發生了什麼，不講為什麼。原本寫的是
   「你把它想得比實際難」——那是我在猜。提早也可能是題目本來就小、
   也可能是他們砍了範圍，系統一個都不知道。 */
RULES.STAMPS = {
  early: { key: 'early', name: '比承諾的早',
           why: '比你自己說的天數早。' },
  exact: { key: 'exact', name: '跟承諾的一樣',
           why: '你說幾天，就是幾天。' },
  late:  { key: 'late',  name: '比承諾的久',
           why: '比你自己說的天數久。這不會拿走任何權利。' }
};

/* 判定：拿實際花的天數比對當初承諾的 */
RULES.judge = function (est, actual) {
  var e = Number(est) || 0, a = Number(actual) || 0, b = RULES.band(e);
  if (a < e - b) return RULES.STAMPS.early;
  if (a > e + b) return RULES.STAMPS.late;
  return RULES.STAMPS.exact;
};

/* 判定的說明句。從數字組出來，所以改 BAND_RATIO 這句話會跟著變。 */
RULES.judgeWhy = function (est, actual) {
  var b = RULES.band(est);
  return '你承諾 ' + est + ' 天，實際花了 ' + actual + ' 天。' +
         '誤差 ' + b + ' 天以內算準（預估的 ' + Math.round(RULES.BAND_RATIO * 100) + '％）。';
};

/* ---------- 他們自己那一份清單 ----------

   本來這裡有兩份我寫死的詞表：八種卡關原因、六種「今天動的是哪一塊」。
   兩份都拿掉了，因為那等於我先替他們定義了「一個專案會做的事」與
   「一個專案會出的錯」。設計系的一天可能是打樣、拍照、找廠商，
   那三個字我一個都想不到——想得到也不該由我想。

   換成一份，而且是那一組自己寫的（存在 Teams.acts，見 40-db.js）。
   同一份清單問三個不同的問題：

     每天      今天動的是哪一件？
     承諾時    哪幾件你覺得會比想的久？
     營火      哪一件真的比你想的久？

   零輸入框那條原則沒有破：清單只寫一次，之後每天都是一下點擊。
   沒寫的組也走得完——那一顆鍵就退回「我今天來過了」。 */
RULES.STEPS_MAX = 12;     /* 一個任務最多分幾段 */

/* ---------- 金幣 ----------
   一件委託 100 枚，做完就有。老師收下時另外給 1–5 枚。
   ── 一格從 1 變 10（使用者的決定）──

   本來是 1–5 枚，上限刻意壓在基本額的 5%，理由寫在下面那一段：
   它是老師的一句話，不是經濟誘因。

   改成 10–50 之後，加成佔一趟總額的 9–33%——它不再只是一句話，
   老師給 10 還是給 50 開始有份量。那是刻意的：二選一（可以／退回）
   太粗，而 1–5 枚在一個 100 起跳的數字旁邊小到看不出差別。

   代價要記著：一個會漲而且看得出差別的數值，會把「做這件事」
   往「拿到那個數字」推。原本的停止規則不變——觀察到學生開始為
   那幾枚做事，就把整層拿掉（見 68-rank.js 的檔頭寫了怎麼拆）。 */
RULES.COIN = { base: 100, bonusMin: 10, bonusMax: 50, bonusStep: 10 };

/* ---------- 你有多確定 ----------
   三階。不進判定，只決定廊道上看得到多遠（light 對到 WORLD.light）。
   看得遠不是獎賞——說「很確定」的人，之後也會被那句話對照。 */
/* redo 是這一階能改幾次承諾。

   本來說「很確定」是免費的：三階只差廊道上看得多遠，其餘什麼都不變。
   免費的宣告不帶任何資訊——沒有理由不說很確定，所以那一格的資料
   也就不代表任何事。

   現在它是一個下注，而賭注是退路：
     很確定    不能改        你把話說死了
     大概吧    可以改一次
     不太確定  可以改兩次    但委託人會多問你一題

   方向是反的，而且是故意的：**說沒把握換到更多幫助**，不是被罰。
   這一格教的是後設認知——知不知道自己什麼時候估不準——
   而懲罰誠實會讓每個人都學會說很確定。 */
RULES.SURE = [
  { key: 'high', name: '很確定',   light: 0, redo: 0 },
  { key: 'mid',  name: '大概吧',   light: 1, redo: 1 },
  { key: 'low',  name: '不太確定', light: 2, redo: 2 }
];
/* 這一趟還能改幾次承諾。

   額度不能記在 run 身上：改承諾會把那一趟標成 rethought，而 runOf
   會跳過 rethought——所以下一次承諾生的是一筆**新的** run，
   記在舊那一筆上的次數等於歸零，機制形同不存在。

   改成數「這一組在這一件委託上已經改過幾次」：rethought 的那幾筆
   本來就留著（走過的那幾天要看得見），數它們就好。

   額度由**這一次**說的把握決定：第一次說不太確定（2 次）、改完之後
   說很確定（0 次），那就不能再改了——他這一次把話說死了。 */
function redoLeft(r) {
  if (!r) return 0;
  var s = RULES.sureOf(r.sure) || RULES.SURE[1];
  var used = where('Runs', function (x) {
    return x.teamId === r.teamId && x.msId === r.msId && x.state === 'rethought';
  }).length;
  return Math.max(0, (s.redo || 0) - used);
}

RULES.sureOf = function (key) {
  for (var i = 0; i < RULES.SURE.length; i++) {
    if (RULES.SURE[i].key === key) return RULES.SURE[i];
  }
  return null;
};

/* ---------- 系統問得多深，跟著走過幾趟走 ----------

   漸進的不是難度（那是老師派的任務），是系統要求他說明自己的深度。
   本來第一趟問得最多——預測哪幾段會拖、勾哪幾段做完、打字寫困境、
   標哪幾天動過。他還沒走過一趟，那些問題答不出來：
   「哪一段比你想的久」對一個沒有上一次的人不成立。

   數字是走完幾趟。走完 2 趟（＝第 3 趟）開始問預測與日子，
   走完 4 趟（＝第 5 趟）開始問困境——那時候他才累積得出那種東西。 */
RULES.ASK = {
  flags: 2,   /* 承諾時：哪幾段會比你想的久 */
  hard:  0    /* 交出去時「為什麼」，要打字。第一趟就問。

                 本來是 4（走完四趟才問），理由是他還沒有那個東西可以講。
                 但一學期大約八趟，第五趟才開始問等於整門課最多寫四次；
                 而這一格是選填，所以擋著它的代價比逼出交差的字更大——
                 沒問過的人不會自己開始寫，選填的框則是他想寫才寫。 */
  /* days 拿掉了：問它的那一頁（收起來）整個不見了。
     留一個沒有人問的問題在規則檔裡是一句謊話。 */
};

/* 走完 n 趟的人，這一題該不該出現。
   回 'new' 代表這一趟剛好是它第一次出現——畫面上要標出來，
   因為「系統問你更多」本身就是走得夠遠的證據。 */
RULES.asks = function (key, done) {
  var need = RULES.ASK[key];
  if (need == null) return 'on';
  var n = Number(done) || 0;
  if (n < need) return 'off';
  return n === need ? 'new' : 'on';
};

/* ---------- 這一趟留下哪一件 ----------

   本來這裡是六句我寫的格言（「下一次一開始就動」）。三選一等於在我的
   六句裡選，那不算自主；而且六句用完就重複，通用到誰都適用，
   也就等於誰都不適用。

   改成：老師勾完可以之後，攤開的三張是這一趟真的發生的三件事，
   用他們自己的詞寫的。學生挑一張當作這一趟的重點。

   三張分別是三個角度，永遠是這三個，不隨機——隨機會讓它跟剛剛
   那幾天斷開，那正是舊版最大的問題：

     days   這幾天你在做什麼      （從每天點的那一下算出來）
     est    你估得怎麼樣          （只比兩個數字）
     over   哪一件比你想的久      （他們自己在營火說的）

   每一張只陳述，不解釋。沒有「所以下一次應該……」——
   那一句一旦寫出來，這個系統就變回一個替他們想結論的東西。 */
RULES.KEEPS = [
  { key: 'days', name: '日誌', tro: 15, eyebrow: '這幾天你在做什麼' },
  { key: 'est',  name: '沙漏', tro: 19, eyebrow: '你估得怎麼樣' },
  { key: 'over', name: '量尺', tro: 2,  eyebrow: '哪一件比你想的久' }
];
RULES.keepOf = function (key) {
  for (var i = 0; i < RULES.KEEPS.length; i++) {
    if (RULES.KEEPS[i].key === key) return RULES.KEEPS[i];
  }
  return null;
};



/* ---------- 老師回一句（協商） ----------

   1 = 這個機制在（預設）。0 = 整個關掉，連那一行都不出現。

   ── 它不佔一個分頁 ──

   本來它是老師那一頁的第三格（審核／剛承諾／出口）。使用者的話：
   「有方式不要讓這流程更複雜但是又不會不拿掉這功能嗎」。

   問題不在功能，在它是**一個要記得去的平行地方**。老師打開系統
   要做的事只有一件——看學生交上來的東西。第三格等於在那件事旁邊
   放一個他必須自己想起來的責任，而他想不起來的時候那一格就是零。

   改法：分頁回到兩格，那件事變成**只在有的時候才出現的一行**，
   出現在他本來就在看的那一頁上（審核）。沒有人在等回話的時候
   那一行完全不存在，所以它不佔任何常態的複雜度。

   ── 為什麼不刪掉 ──

   這個機制是這個作品裡唯一「老師可以在事情發生之前說話」的地方，
   其餘每一個接觸點都是事後的（收下、退回，都是對著已經做完的東西）。
   它也是「自主不等於不受干涉」那一整段的實作，而且是這套判定唯一
   擋得住「把天數報寬一點」的管道——系統測不出灌水，人看得出來。

   第一次進教室先關掉是合理的：老師那一頁本來有三格（審核／剛承諾／
   出口），而他第一天真正要做的只有一件事——看學生交上來的東西。
   多一格就是多一件他要煩惱的事。

   關掉的代價要講清楚：**現場不會產生任何協商資料**。
   estFirst／askEst／est 那三個數字（他一個人說的、老師說的、
   最後定的）一筆都不會有，而那三個數字是論文第六章要的東西。

   所以做成開關：程式全部留著（actAskEst／actAnswerAsk／PAGES.askest
   一行都沒動），要收那份資料的時候把這裡改成 1 就回來了。 */
RULES.ASK = 1;

/* ---------- 停滯 ----------
   系統不發「已逾期」通知。狀態本身就是回饋：幾天沒推進，畫面自己會暗下來。
   這是勸導式設計的核心——不指責，只是讓停下來這件事看得見。 */
RULES.stallOf = function (lastPushAt, nowTs) {
  if (!lastPushAt) return { level: 0, days: 0 };
  var days = Math.floor((nowTs - lastPushAt) / 86400000);
  if (days >= RULES.SLEEP_DAYS) return { level: 2, days: days };   /* 睡著 */
  if (days >= RULES.STALL_DAYS) return { level: 1, days: days };   /* 長藤蔓 */
  return { level: 0, days: days };
};

/* 停滯的說法。不講「你逾期了」，講畫面上發生了什麼。
   而且講的是他自己說的那個數字，不是我規定的期限。 */
/* 本來是「水漫過來了／水淹過頭了」——那講的是 .tide，橫著漫過來的
   那片藍色水。它拿掉了，所以那兩句在描述畫面上沒有的東西。

   照現在真的畫出來的東西講：第一階他身上爬藤蔓，第二階他睡著了。 */
RULES.stallSay = function (level, days) {
  if (level === 2) return '他睡著了。比你自己說的多 ' + days + ' 天。';
  if (level === 1) return '藤蔓爬上來了。比你自己說的多 ' + days + ' 天。';
  return '';
};

/* ---------- 走到哪了 ----------
   迷霧走廊的長度＝承諾的天數。推進一次前進一格。
   走完不等於完成——完成是上傳作業那一刻。 */
RULES.progress = function (pushes, est) {
  var e = Math.max(1, Number(est) || 1);
  return clamp(0, 1, (Number(pushes) || 0) / e);
};
