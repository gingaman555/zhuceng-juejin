/* 一點小差別：頭上、手邊、身上。體型已經拉開了，這一層只是讓
   同一種體型的幾個人不完全一樣。 */
var PAT_MARK = {
  none: null,
  lamp: { px: ['+*+', '###', '+#+'], x: 1, y: 7 },
  staff: { px: ['*', '#', '#', '#', '#', '#', '#'], x: 21, y: 4 },
  horn: { px: ['*....*', '+#..#+'], x: 9, y: 0 },
  bag: { px: ['+###+', '#####', '+###+'], x: 18, y: 8 },
  /* 一點光。放在左邊緣，不然它會落在身體的反光上、等於沒畫。 */
  eye: { px: ['*', '.', '*'], x: 5, y: 6 },
  drip: { px: ['+', '#', '+'], x: 4, y: 11 }
};

function patNew() {
  var g = [], y, x;
  for (y = 0; y < PAT_H; y++) { var r = []; for (x = 0; x < PAT_W; x++) r.push('.'); g.push(r); }
  return g;
}
function patPut(g, art, x0, y0) {
  art.forEach(function (row, dy) {
    for (var dx = 0; dx < row.length; dx++) {
      var c = row[dx];
      if (c === '.') continue;
      var x = x0 + dx, y = y0 + dy;
      if (x >= 0 && x < PAT_W && y >= 0 && y < PAT_H) g[y][x] = c;
    }
  });
}

/* 一個委託人。體型置中、貼著地面那一列，所以誰都不會浮著或站歪。 */
function patPx(body, mark) {
  var b = PAT_BODY[body] || PAT_BODY.tall;
  var w = 0;
  b.forEach(function (r) { if (r.length > w) w = r.length; });
  var g = patNew();
  patPut(g, b, Math.max(0, Math.round((PAT_W - w) / 2)), Math.max(0, PAT_H - b.length));
  var m = PAT_MARK[mark || 'none'];
  if (m) patPut(g, m.px, m.x, m.y);
  return g.map(function (r) { return r.join(''); });
}

/* ---------- 誰長什麼樣 ----------

   照名字對。名字、住哪一區、那一句描述都不動——那些寫得很好，
   而且它們本來就是觀察句，拿來寫一個奇怪的委託人剛剛好。

   同一種體型最多出現三次，而且配不同的小記號。 */
/* 幾位刻意指定的。其餘照名字的最後一個字配（見下面 PAT_TAIL）。 */
var PATRON_LOOK = {
  '霧潛母': ['drape', 'none'],
  '灰擬者': ['twin', 'eye'],
  '塵銜獸': ['haul', 'bag'],
  '晶面獸': ['shell', 'eye'],
  '影漲母': ['hood', 'none'],
  '垂根者': ['long', 'drip'],
  '苔面': ['squat', 'none'],
  '殘架': ['tall', 'none'],
  '磁滯者': ['float', 'eye'],
  '螺紋母': ['bighead', 'staff']
};

/* 名字的最後一個字決定體型。

   這些名字本來就有規律，照它配剪影就跟名字對得上——
   群是一堆、母是大的、者是人形的、獸是矮壯的、面是有殼的。
   一個字給兩三種，用雜湊在裡面挑，同一個字尾的幾位才不會長一樣。 */
var PAT_TAIL = {
  '群': ['swarm', 'stack'],
  '母': ['drape', 'bighead', 'hood'],
  '者': ['tall', 'hood', 'float'],
  '獸': ['squat', 'haul', 'bighead'],
  '面': ['shell', 'bighead'],
  '蟲': ['stack', 'long'],
  '甲': ['shell'],
  '架': ['tall', 'stack'],
  '囊': ['drape', 'squat']
};
var PAT_KEYS = Object.keys(PAT_BODY);
var PAT_MKEYS = Object.keys(PAT_MARK);

function dressPatrons() {
  /* 先決定每一位的體型。 */
  var body = {};
  allFauna().forEach(function (c) {
    var look = PATRON_LOOK[c.n];
    if (look) { body[c.n] = look[0]; return; }
    var tail = PAT_TAIL[String(c.n).slice(-1)] || PAT_KEYS;
    body[c.n] = tail[hash(c.n) % tail.length];
  });
  /* 再在同一種體型裡把記號輪流發下去。

     本來記號也是雜湊決定的，所以體型跟記號同時撞的時候，
     兩位就長得一模一樣（34 位裡發生了 8 次）。輪流發就不會——
     12 種體型 × 7 種記號有 84 種組合，34 位放得下。 */
  /* 指名的那幾位先佔位，其餘的再挑還沒被用掉的——
     不然生出來的會撞到指名的（發生過 5 次）。 */
  var taken = {};
  allFauna().forEach(function (c) {
    var f = PATRON_LOOK[c.n];
    if (f) taken[f[0] + '|' + f[1]] = 1;
  });
  allFauna().forEach(function (c) {
    var bd = body[c.n];
    var f = PATRON_LOOK[c.n];
    var mk;
    if (f) {
      mk = f[1];
    } else {
      /* 這個體型還沒被用掉的第一個記號。12 種體型 × 7 種記號 = 84 種，
         34 位一定放得下。 */
      for (var i = 0; i < PAT_MKEYS.length; i++) {
        if (!taken[bd + '|' + PAT_MKEYS[i]]) { mk = PAT_MKEYS[i]; break; }
      }
      if (!mk) mk = PAT_MKEYS[hash(c.n) % PAT_MKEYS.length];
      taken[bd + '|' + mk] = 1;
    }
    c.px = patPx(bd, mk);
  });
}

/* 一載入就換掉。名字、住哪一區、描述都不動——只換圖。 */
dressPatrons();
