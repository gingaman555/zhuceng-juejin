function animVineBreak(onDone) {
  var el = document.querySelector('.hero .vine');
  if (!el) { if (onDone) onDone(); return; }
  playFrames(el, VINE_BREAK.map(function (px) { return [px, VINE.pal]; }), 90, function () {
    el.style.display = 'none';
    if (onDone) onDone();
  });
}

