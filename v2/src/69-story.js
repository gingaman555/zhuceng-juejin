function storyMap(t) {
  var seed = t ? t.classId : 'C1';
  var here = t ? zoneNow(t.teamId) : STRATA[0];
  var H = ['<div class="sty-art sty-map">'];
  H.push('<div class="sty-rooms">');
  STRATA.forEach(function (z) {
    /* 你現在在的那一個標出來——這張圖上唯一跟「你」有關的資訊。 */
    H.push('<div class="sty-room ' + z.key + (z.key === here.key ? ' here' : '') + '">');
    /* 那個地方真的長什麼樣（見 18-places.js）。本來這裡是一塊換了顏色的
       方塊，圖上沒有名字沒講過的任何東西——「水晶迴廊」四個字旁邊
       一顆水晶都沒有。 */
    /* 圖歸圖，名字歸名字。名字壓在圖上會把每個地方最下面那一段
       （碎石、水、軌道、熱源）吃掉，而那一段正是它們各自的樣子。 */
    H.push('<span class="sty-pic">');
    H.push(placeArt(z, ''));
    if (z.key === here.key) {
      H.push('<span class="sty-me">' +
        pxTag(HERO.idleA, HERO.pal, 'wf wa') + pxTag(HERO.idleB, HERO.pal, 'wf wb') +
        '</span>');
    }
    /* ── 每一個地方都有人在等 ──

       這一頁的那一句是「你是下來接委託的人」，可是圖上本來只有
       六個空房間跟你自己——**委託**那兩個字在圖上完全沒有對應物。
       那張圖答得出「這裡有六個地方」，答不出「你為什麼下來」。

       每一個地方放一位站在那裡的委託人（那一層真的會出現的那一位，
       見 faunaOf），你在的那一間他站在你旁邊。六個地方六個人在等，
       那一句話就不用光靠文字撐著。 */
    var who = faunaOf(z.key)[0];
    if (who) {
      H.push('<span class="sty-wait">' + patTag(who, z.pal, '') + '</span>');
    }
    H.push('</span>');
    H.push('<em>' + esc(z.name) + '</em>');
    H.push('</div>');
  });
  H.push('</div>');
  /* 關著的那一扇。它不是第七個地方——它是唯一的出去。 */
  H.push('<div class="sty-door"><i></i><b>出口</b></div>');
  H.push('</div>');
  return H.join('');
}

