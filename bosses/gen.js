function toSvg(b, opt) {
  opt = opt || {};
  const S = 24, rows = b.px;
  const out = [];
  out.push('<svg viewBox="0 0 ' + S + ' ' + S + '" shape-rendering="crispEdges" xmlns="http://www.w3.org/2000/svg" style="width:100%;height:100%;display:block">');
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === '.') { x++; continue; }
      let w = 1;
      while (x + w < row.length && row[x + w] === c) w++;
      const fill = b.hue[c] || b.hue['#'];
      const op = c === '~' ? ' opacity=".55"' : '';
      out.push('<rect x="' + x + '" y="' + y + '" width="' + w + '" height="1" fill="' + fill + '"' + op + '/>');
      x += w;
    }
  });
  out.push('</svg>');
  return out.join('');
}

